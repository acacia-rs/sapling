"""Transcribes the coral crust templates (behaviour pack structures/coralcrust, legacy Bedrock-flavoured .nbt)
into src/feature/data/coral_crust.rs for src/feature/coral/crust.rs.

    py -3 -I scripts/coral_data.py <bds>

Per template: its blocks in file order as (x, y, z, kind) and its data structure blocks (`blockMarker`,
`anchor`) in file order, the order `LegacyStructureTemplate::getMarkers` inserts them. Kinds index KINDS.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from templates_to_rust import load  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'src', 'feature', 'data', 'coral_crust.rs')
# The templates' legacy palette as BDS places it (oracle census of the warm ocean region, 2026-10-08:
# `coral_block[variant=dead_coral]` lands as dead bubble coral).
KINDS = {('minecraft:coral_block', 'dead_coral'): 'DeadBubbleCoralBlock', ('minecraft:stone', 'andesite'): 'Andesite',
         ('minecraft:stone', 'diorite'): 'Diorite', ('minecraft:stone', 'granite'): 'Granite', ('minecraft:sand', 'sand'): 'Sand'}
ORDER = list(KINDS)
MARKER = 'minecraft:structure_block'
NAMES = [f'crust{i}' for i in range(1, 6)] + [f'outcropping{i}' for i in range(1, 7)]


def template(path):
    t = load(path)
    palette = [(s['Name'], s.get('Properties', {}).get('variant', s.get('Properties', {}).get('mode'))) for s in t['palette']]
    blocks, markers = [], []
    for b in t['blocks']:
        x, y, z = b['pos']
        name, variant = palette[b['state']]
        if name == MARKER:
            assert variant == 'data', (path, variant)
            markers.append(f'({x}, {y}, {z})')
        else:
            blocks.append(f'({x}, {y}, {z}, {ORDER.index((name, variant))})')
    return f'Crust {{ blocks: &[{", ".join(blocks)}], markers: &[{", ".join(markers)}] }}'


def main():
    base = os.path.join(sys.argv[1], 'behavior_packs', 'vanilla', 'structures', 'coralcrust')
    lines = ['// Generated by scripts/coral_data.py from BDS 1.26.52 vanilla behaviour packs (structures/coralcrust).',
             'use crate::block::Block;', '',
             '/// A coral crust template: blocks as (x, y, z, index into `KINDS`), data markers, both in file order.',
             'pub struct Crust {', '    pub blocks: &\'static [(u8, u8, u8, u8)],', '    pub markers: &\'static [(u8, u8, u8)],', '}', '',
             f'pub const KINDS: [Block; {len(ORDER)}] = [{", ".join("Block::" + KINDS[k] for k in ORDER)}];', '',
             '/// crust1..5, then outcropping1..6.', f'pub static CRUSTS: [Crust; {len(NAMES)}] = [']
    lines += [f'    {template(os.path.join(base, name + ".nbt"))},' for name in NAMES]
    with open(OUT, 'w', encoding='utf-8', newline='\n') as out:
        out.write('\n'.join(lines + ['];']) + '\n')


if __name__ == '__main__':
    main()
