"""Transcribes the overworld biomes' surface builders from BDS's vanilla behaviour packs into
src/surface/biomes.rs.

    py -3 -I scripts/surface_to_rust.py <bds> > src/surface/biomes.rs

Biome files are read as bds_packs.documents describes.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from bds_packs import IDS, biomes  # noqa: E402

BLOCKS = {
    'stone': 'Stone', 'dirt': 'Dirt', 'grass_block': 'GrassBlock', 'sand': 'Sand', 'red_sand': 'RedSand',
    'gravel': 'Gravel', 'water': 'Water', 'mycelium': 'Mycelium', 'snow': 'Snow', 'ice': 'Ice',
    'packed_ice': 'PackedIce', 'powder_snow': 'PowderSnow', 'calcite': 'Calcite', 'mud': 'Mud',
    'podzol': 'Podzol', 'coarse_dirt': 'CoarseDirt', 'hardened_clay': 'Terracotta',
    'white_terracotta': 'WhiteTerracotta', 'bedrock': 'Bedrock', 'sulfur': 'Sulfur', 'cinnabar': 'Cinnabar',
}


def block(value):
    if isinstance(value, dict):
        name = value['name'].removeprefix('minecraft:')
        if name == 'dirt' and value.get('states', {}).get('dirt_type') == 'coarse':
            name = 'coarse_dirt'
    else:
        name = value.removeprefix('minecraft:')
    return 'Block::' + BLOCKS[name]


def adjustments(components):
    out = []
    for adj in components.get('minecraft:surface_material_adjustments', {}).get('adjustments', []):
        assert 'height_range' not in adj, 'height ranges are not transcribed'
        m = adj['materials']
        fields = ', '.join(f'{k}: {("Some(" + block(m[k]) + ")") if k in m else "None"}'
                           for k in ('top_material', 'mid_material', 'sea_floor_material', 'foundation_material'))
        lo, hi = adj['noise_range']
        scale = adj.get('noise_frequency_scale', 1.0)
        out.append(f'Adjustment {{ noise_scale: {float(scale)!r}, range: [{float(lo)!r}, {float(hi)!r}], {fields} }}')
    return out


def steep(components):
    params = components.get('minecraft:mountain_parameters', {}).get('steep_material_adjustment')
    if not params:
        return 'None'
    flags = ', '.join(f'{d}: {str(params.get(d + "_slopes", False)).lower()}' for d in ('north', 'south', 'east', 'west'))
    return f'Some(Steep {{ material: {block(params["material"])}, {flags} }})'


def main():
    found = biomes(sys.argv[1])
    print('// Generated by scripts/surface_to_rust.py from BDS 1.26.52 vanilla behaviour packs.')
    print('use super::spec::{Adjustment, Builder, Gradient, Mesa, Materials, Steep, SurfaceSpec};')
    print('use crate::block::Block;')
    print()
    print('pub fn surface_spec(biome: u32) -> Option<SurfaceSpec> {')
    print('    Some(match biome {')
    for name, biome_id in sorted(IDS.items(), key=lambda kv: kv[1]):
        components = found[name]['minecraft:biome']['components']
        builder = components['minecraft:surface_builder']['builder']
        kind = builder['type'].removeprefix('minecraft:')
        if kind == 'noise_gradient':
            print(f'        {biome_id} => return None, // {name}: noise_gradient, not ported')
            continue
        materials = (f'Materials {{ top: {block(builder["top_material"])}, mid: {block(builder["mid_material"])}, '
                     f'sea_floor: {block(builder["sea_floor_material"])}, foundation: {block(builder["foundation_material"])}, '
                     f'sea: {block(builder["sea_material"])} }}')
        if kind == 'overworld':
            built = 'Builder::Overworld'
        elif kind == 'frozen_ocean':
            built = 'Builder::FrozenOcean'
        elif kind == 'swamp':
            built = f'Builder::Swamp {{ max_puddle_depth: {builder["max_puddle_depth_below_sea_level"]} }}'
        elif kind == 'mesa':
            built = (f'Builder::Mesa(Mesa {{ bryce_pillars: {str(builder["bryce_pillars"]).lower()}, '
                     f'has_forest: {str(builder["has_forest"]).lower()} }})')
        else:
            raise SystemExit(f'{name}: unknown builder {kind}')
        temperature = float(components['minecraft:climate']['temperature'])
        adj = adjustments(components)
        print(f'        {biome_id} => SurfaceSpec {{ // {name}')
        print(f'            builder: {built}, sea_floor_depth: {builder["sea_floor_depth"]}, temperature: {temperature!r},')
        print(f'            materials: {materials},')
        print(f'            adjustments: &[{", ".join(adj)}], steep: {steep(components)},')
        print('        },')
    print('        _ => return None,')
    print('    })')
    print('}')
    print()
    print('/// The `minecraft:subsurface_builder` of a biome (only noise gradients exist).')
    print('pub fn subsurface_spec(biome: u32) -> Option<Gradient> {')
    print('    Some(match biome {')
    for name, biome_id in sorted(IDS.items(), key=lambda kv: kv[1]):
        sub = found[name]['minecraft:biome']['components'].get('minecraft:subsurface_builder')
        if sub:
            print(f'        {biome_id} => {gradient(sub["builder"])}, // {name}')
    print('        _ => return None,')
    print('    })')
    print('}')


def gradient(builder):
    assert builder['type'] == 'minecraft:noise_gradient', builder['type']
    noise = builder['noise_descriptor']
    amplitudes = ', '.join(repr(float(a)) for a in noise['amplitudes'])
    keep = ', '.join(block(b) for b in builder.get('non_replaceable_blocks', []))
    bands = ', '.join(f'({float(s["range"]["min"])!r}, {float(s["range"]["max"])!r}, {block(s["block"])})'
                      for s in builder['noise_block_specifiers'])
    return (f'Gradient {{ noise: "{noise["name"]}", first_octave: {noise["first_octave"]}, amplitudes: &[{amplitudes}], '
            f'keep: &[{keep}], bands: &[{bands}] }}')


main()
