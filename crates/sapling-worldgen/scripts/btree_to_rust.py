# Converts a cubiomes biome tree header (tables/btreeNNN.h, MIT, Copyright (c) 2020 Cubitect)
# into src/biome/btree/{params,nodes}.rs.
#   py -3 scripts/btree_to_rust.py <cubiomes>/tables/btree262.h src/biome/btree
import re
import sys

source, out_dir = sys.argv[1], sys.argv[2]
text = open(source).read()
name = re.search(r'enum \{ (btree\w+)_order = (\d+) \}', text)
order = int(name.group(2))
steps = [int(v) for v in re.search(r'_steps\[\] = \{([^}]*)\}', text).group(1).split(',')]
params = [(int(a), int(b)) for a, b in re.findall(r'\{\s*(-?\d+),\s*(-?\d+)\}', text.split('_param[][2] =')[1].split('};')[0])]
nodes = re.findall(r'0x[0-9A-Fa-f]{16}', text.split('_nodes[] =')[1])

header = '// Generated by scripts/btree_to_rust.py from cubiomes {} (MIT, Copyright (c) 2020 Cubitect).\n'.format(name.group(1))

with open(f'{out_dir}/params.rs', 'w', newline='\n') as f:
    f.write(header)
    f.write(f'pub const ORDER: usize = {order};\n')
    f.write(f'pub const STEPS: [usize; {len(steps)}] = {steps};\n')
    f.write(f'/// Quantized (x10000) parameter ranges that nodes index by byte.\npub const PARAMS: [[i64; 2]; {len(params)}] = [\n')
    for i in range(0, len(params), 8):
        f.write('    ' + ' '.join(f'[{a}, {b}],' for a, b in params[i:i + 8]) + '\n')
    f.write('];\n')

with open(f'{out_dir}/nodes.rs', 'w', newline='\n') as f:
    f.write(header)
    f.write(f'pub const NODES: [u64; {len(nodes)}] = [\n')
    for i in range(0, len(nodes), 32):
        f.write('    ' + ', '.join(nodes[i:i + 32]) + ',\n')
    f.write('];\n')
print(len(params), 'params', len(nodes), 'nodes')
