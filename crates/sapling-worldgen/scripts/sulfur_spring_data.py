"""Transcribes the sulfur spring templates (behaviour pack structures/minecraft/sulfur_spring_*.mcstructure) into
src/feature/data/sulfur_springs.rs for src/feature/sulfur_spring.rs.

    python3 -I scripts/sulfur_spring_data.py <bds>

Per template: its size and its non-void cells in index order (x, then y, then z) as (x, y, z, kind), air
included; a cell whose second layer holds water takes the block's waterlogged twin. Kinds index KINDS. Then the
cells carrying `tick_queue_data` (the potent sulfur), with their tick delays.
"""
import os
import re
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mcstructure  # noqa: E402
from blocks_data import block  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'src', 'feature', 'data', 'sulfur_springs.rs')
PACK = os.path.join('behavior_packs', 'vanilla_1.26.30', 'structures', 'minecraft')
NAMES = [f'small_{i}' for i in range(1, 5)] + [f'medium_{i}' for i in range(1, 4)] + ['large_1', 'large_2', 'extra_large_1']
VARIANTS = set(re.findall(r'(\w+) => "', ''.join(open(os.path.join(HERE, '..', 'src', 'block', t), encoding='utf-8').read()
                                                  for t in os.listdir(os.path.join(HERE, '..', 'src', 'block')) if t.endswith('table.rs'))))


def kind(entry, wet):
    variant = block({'name': entry['name'], 'states': entry.get('states', {})}).removeprefix('Block::')
    if wet:
        variant += 'Wet'
        assert variant in VARIANTS, variant
    return 'Block::' + variant


def template(bds, name, kinds):
    data = open(os.path.join(bds, PACK, f'sulfur_spring_{name}.mcstructure'), 'rb').read()
    root, _ = mcstructure._read(data, 3 + struct.unpack_from('<H', data, 1)[0], 10)
    sx, sy, sz = root['size']
    palette = root['structure']['palette']['default']['block_palette']
    positions = root['structure']['palette']['default'].get('block_position_data', {})
    primary, extra = root['structure']['block_indices']
    cells = []
    ticks = []
    for index, entry in sorted(positions.items(), key=lambda item: int(item[0])):
        i = int(index)
        delays = [str(tick['tick_delay']) for tick in entry.get('tick_queue_data', [])]
        if delays:
            ticks.append(f'({i // (sy * sz)}, {i // sz % sy}, {i % sz}, &[{", ".join(delays)}])')
    for index, state in enumerate(primary):
        if state < 0:
            continue
        wet = extra[index] >= 0
        assert not wet or palette[extra[index]]['name'] == 'minecraft:water', (name, index)
        rust = kind(palette[state], wet)
        if rust not in kinds:
            kinds.append(rust)
        cells.append(f'({index // (sy * sz)}, {index // sz % sy}, {index % sz}, {kinds.index(rust)})')
    return f'SpringTemplate {{ size: [{sx}, {sy}, {sz}], cells: &[{", ".join(cells)}], ticks: &[{", ".join(ticks)}] }}'


def main():
    kinds = []
    templates = [template(sys.argv[1], name, kinds) for name in NAMES]
    lines = ['// Generated by scripts/sulfur_spring_data.py from BDS 1.26.52 vanilla behaviour packs (sulfur_spring_*.mcstructure).',
             'use crate::block::Block;', '',
             '/// A sulfur spring template: its size and its non-void cells in index order as (x, y, z, index into `KINDS`).',
             'pub struct SpringTemplate {', '    pub size: [i32; 3],', "    pub cells: &'static [(u8, u8, u8, u8)],",
             '    /// `tick_queue_data`: the cells (x, y, z) that queue ticks when placed, and their delays in order.',
             "    pub ticks: &'static [(u8, u8, u8, &'static [u32])],", '}', '',
             f'pub const KINDS: [Block; {len(kinds)}] = [{", ".join(kinds)}];', '',
             '/// By structure name.', f'pub static TEMPLATES: [(&str, SpringTemplate); {len(NAMES)}] = [']
    lines += [f'    ("minecraft:sulfur_spring_{name}", {t}),' for name, t in zip(NAMES, templates)]
    with open(OUT, 'w', encoding='utf-8', newline='\n') as out:
        out.write('\n'.join(lines + ['];']) + '\n')


if __name__ == '__main__':
    main()
