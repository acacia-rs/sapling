"""Writes src/feature/liquid/detect_table.rs from scripts/data/block_liquid.tsv (scripts/dbg_liquid.py's registry walk):
the block types water flows into, those whose `on_touch` byte is not 2 (blocking).

usage: py -3 -I liquid_data.py
"""
import os
import textwrap

HERE = os.path.dirname(os.path.abspath(__file__))
BLOCKING = 2


def main():
    open_names, mixed = [], []
    for line in open(os.path.join(HERE, 'data', 'block_liquid.tsv')):
        fields = line.rstrip('\n').split('\t')
        name, on_touch = fields[0].removeprefix('minecraft:'), int(fields[4])
        if len(fields) > 6:
            mixed.append(name)
        if on_touch != BLOCKING:
            open_names.append(name)
    assert not mixed, f'types whose states differ: {mixed}'
    lines = textwrap.wrap(' '.join(sorted(set(open_names))), 104)
    body = ' \\\n     '.join(lines)
    out = (
        '//! Generated by scripts/liquid_data.py from BDS\'s block registry (scripts/data/block_liquid.tsv); do not edit.\n\n'
        '/// The block types water flows into (`Block` +0xba is not 2); every other type holds it out.\n'
        f'pub(super) const GIVES_WAY: &str = "{body}";\n'
    )
    with open(os.path.join(HERE, '..', 'src', 'feature', 'liquid', 'detect_table.rs'), 'w', newline='\n') as f:
        f.write(out)
    print(len(set(open_names)), 'types give way')


if __name__ == '__main__':
    main()
