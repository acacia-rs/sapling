"""Writes src/block/support_table.rs from scripts/data/block_types.tsv (scripts/dbg_blocks.py's registry walk):
every block type's support class, read off its `canProvideSupport` and `canProvideMultifaceSupport`
functions, its `minecraft:support` component and its properties.

usage: py -3 -I support_data.py
"""
import collections
import os
import textwrap

HERE = os.path.dirname(os.path.abspath(__file__))
SOLID_BLOCKING, TOP = 0x40000, 0x20000
# canProvideSupport implementations (image 6ab54bee) by class; None is the default, decided by the properties.
FUNCTIONS = {
    '141a24e20': None,
    '140076010': 'Open',
    '1400a2880': 'Solid',  # pistons: always
    '141a3b1c0': 'Down',
    '141a2cfe0': 'DownCentre',
    '142fcec40': 'DownCentre',
    '1425e5d10': 'EndsCentre',
    '146608870': 'EndsCentre',
    '146603600': 'Slab',
    '1425764f0': 'Trapdoor',
    '148b220d0': 'Chain',
    '141a45250': 'Cauldron',
    '148b33d80': 'Composter',
    '142fd2950': 'Up',
    # By states sapling never meets: grindstone, skulls, shelves, end rod, lightning rods, piston arms, snow layers.
    '142fce030': 'Open', '146602890': 'Open', '148b51e20': 'Open', '148a32230': 'Open', '148b5bff0': 'Open',
    '1465f9f90': 'Open', '1471fd8f0': 'Open',
}
MULTIFACE = {'1400a2880': 'Leaves', '142fd2950': 'Azalea'}
COMPONENT = {'0': 'Fence', '1': 'Stair'}


def classify(support, multiface, properties, component):
    if multiface in MULTIFACE:
        return MULTIFACE[multiface]
    if component in COMPONENT:
        return COMPONENT[component]
    named = FUNCTIONS[support]
    if named == 'Slab' and properties & SOLID_BLOCKING:
        return 'Solid'  # double slabs
    if named:
        return named
    return 'Solid' if properties & SOLID_BLOCKING else 'Top' if properties & TOP else 'Open'


def literal(names):
    lines = textwrap.wrap(' '.join(sorted(names)), 104)
    return '"' + ' \\\n         '.join(lines) + '"'


def main():
    classes, blocking = collections.defaultdict(list), []
    for line in open(os.path.join(HERE, 'data', 'block_types.tsv')):
        if line.startswith('#') or not line.strip():
            continue
        name, _, support, multiface, properties, _, _, _, component = line.rstrip('\n').split('\t')
        name, properties = name.removeprefix('minecraft:'), int(properties, 16)
        kind = classify(support, multiface, properties, component)
        if kind != 'Solid':
            classes[kind].append(name)
            if properties & SOLID_BLOCKING:
                blocking.append(name)
    out = ['//! Generated by scripts/support_data.py from BDS\'s block registry (scripts/data/block_types.tsv); do not edit.',
           '', 'use super::support::Class;', '',
           '/// Block names by support class; a name in no list is `Class::Solid`.',
           'pub(super) const CLASSES: &[(Class, &str)] = &[']
    for kind in sorted(classes):
        out.append(f'    (Class::{kind},\n     {literal(classes[kind])}),')
    out += ['];', '', '/// The blocks above that have the solid-blocking property all the same.',
            f'pub(super) const SOLID_BLOCKING: &str =\n    {literal(blocking)};', '']
    path = os.path.join(HERE, '..', 'src', 'block', 'support_table.rs')
    open(path, 'w', newline='\n').write('\n'.join(out))
    print({kind: len(names) for kind, names in classes.items()}, len(blocking))


main()
