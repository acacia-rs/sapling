//! Drills of `/execute`: each sub-command as it works and as it fails (`execute`), its
//! conditions (`execute-if`), and what it does to the command it runs and its answer (`execute-run`).

/// Packets shown of these drills.
pub const EXECUTE_SHOWN: &[&str] = &["UpdateBlock", "AddEntity", "MovePlayer", "MoveEntityAbsolute", "RemoveEntity", "InventorySlot", "SetScore"];

/// The drill called `name` of this file.
pub fn drill(name: &str) -> Option<(Vec<String>, &'static [&'static str])> {
    let lines = match name {
        "execute" => EXECUTE,
        "execute-if" => CONDITIONS,
        "execute-run" => RUNS,
        "execute2" => ANCHORS,
        _ => return None,
    };
    Some((lines.iter().map(|line| line.to_string()).collect(), EXECUTE_SHOWN))
}

