//! Drills of the commands that mostly tell clients something: `/loot` (`lootcmd`), the camera,
//! fog, HUD, music, animation and daylock commands (`screen`), and `/recipe`, `/inputpermission`,
//! `/mobevent`, `/event`, `/dialogue` and `/ability` (`controls`).

/// Packets shown of these drills; `Unknown` prints packets the decoder has no name for.
pub const CLIENT_SHOWN: &[&str] = &[
    "CameraShake", "CameraInstruction", "PlayerFog", "SetHud", "AnimateEntity", "UnlockedRecipes", "UpdateClientInputLocks", "NpcDialogue", "GameRulesChanged", "PlaySound", "StopSound",
    "ClientboundUpdateSoundData", "UpdateAbilities", "EntityEvent", "ActorEvent", "InventorySlot", "InventoryContent", "AddItemEntity", "AddEntity", "UpdateBlock", "SetEntityData", "Unknown",
];

/// The drill called `name` of this file.
pub fn drill(name: &str) -> Option<(Vec<String>, &'static [&'static str])> {
    let lines = match name {
        "lootcmd" => LOOT,
        "lootcmd2" => LOOT2,
        "screen" => SCREEN,
        "controls" => CONTROLS,
        "controls2" => CONTROLS2,
        "music" => return Some((MUSIC.iter().map(|line| line.to_string()).collect(), &["LevelEventGeneric"])),
        _ => return None,
    };
    Some((lines.iter().map(|line| line.to_string()).collect(), CLIENT_SHOWN))
}

