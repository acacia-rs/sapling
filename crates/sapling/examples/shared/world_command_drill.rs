fn owned(sets: &[&[&str]]) -> Vec<String> {
    sets.iter().flat_map(|lines| lines.iter().map(|line| line.to_string())).collect()
}

pub fn world() -> Vec<String> {
    let help: Vec<String> = HELP.iter().map(|command| format!("help {command}")).collect();
    [help, owned(&[SPAWNS, SERVER, FILLS, CLONES, SPREAD, TRANSFER])].concat()
}

pub fn items() -> Vec<String> {
    owned(&[ITEMS])
}
