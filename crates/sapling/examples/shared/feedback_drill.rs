pub fn feedback() -> Vec<String> {
    let mut lines = Vec::new();
    for rule in ["true", "false", "true"] {
        lines.extend([format!("gamerule sendcommandfeedback {rule}"), String::new()]);
        lines.extend(COMMANDS.map(String::from));
        lines.push(String::new());
    }
    lines
}
